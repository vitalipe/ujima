(ns build.deps
  "The pinned bb-deps manifest (os/build/deps-pin.edn): what the device's bb
   needs beyond its built-ins. pin! resolves deps.edn — the single deps site —
   on the host (java is fine at tool-time) and commits the closure as
   coordinates + urls + sha256s; the install stage downloads per manifest into
   the image's /ujima/m2 — plain HTTP, no resolver, no JVM. A manifest change
   ships only after the vendor cache is rebuilt (rm out/cache/<name>.img),
   same as packages."
  (:require [clojure.string  :as str]
            [clojure.java.io :as io]
            [clojure.edn     :as edn]
            [babashka.fs      :as fs]
            [babashka.process :as p]))


(def ^:private manifest-file "os/build/deps-pin.edn")

(def ^:private repos ["https://repo.clojars.org" "https://repo1.maven.org/maven2"])

;; bb IS the clojure runtime
(def ^:private clojure-own
  #{"org/clojure/clojure/" "org/clojure/spec.alpha/" "org/clojure/core.specs.alpha/"})


(defn- sha256 [f]
  (let [d (java.security.MessageDigest/getInstance "SHA-256")]
    (str/join (map #(format "%02x" %) (.digest d (fs/read-all-bytes f))))))


;; ── pin! (host, explicit tool-time — like bb pin schema) ────────────────────────

(defn- device-deps []
  (:deps (edn/read-string (slurp "deps.edn"))))

(defn- resolve-jars
  "The closure of DEPS as local m2 jar paths — an isolated bb resolution in a
   temp config, so bb.edn's bundled libs never contaminate the set."
  [deps]
  (let [dir (str (fs/create-temp-dir))]
    (spit (str dir "/bb.edn") (pr-str {:paths [] :deps deps}))
    (->> (str/split (:out (p/shell {:dir dir :out :string}
                                   "bb" "-e" "(require '[babashka.classpath :as cp]) (print (cp/get-classpath))"))
                    #":")
         (map str/trim)
         (filter #(str/ends-with? % ".jar")))))

(defn- locate
  "The repo that actually serves REL (clojars first, then central)."
  [rel]
  (or (first (filter (fn [base]
                       (zero? (:exit (p/shell {:continue true :out :string :err :string}
                                              "curl" "-sfI" "--max-time" "10" (str base "/" rel)))))
                     repos))
      (throw (ex-info "no repo serves this artifact" {:jar rel}))))

(defn pin!
  "Rewrite the manifest from deps.edn. Review the diff, commit."
  []
  (let [entries (->> (resolve-jars (device-deps))
                     (map (fn [jar] {:jar jar :path (last (str/split jar #"/repository/"))}))
                     (remove (fn [{:keys [path]}] (some #(str/starts-with? path %) clojure-own)))
                     (sort-by :path)
                     (mapv (fn [{:keys [jar path]}]
                             {:path   path
                              :url    (str (locate path) "/" path)
                              :sha256 (sha256 jar)})))]
    (spit manifest-file
          (str ";; GENERATED by build.deps (bb pin deps) — do not edit. The install stage\n"
               ";; downloads exactly these into the image's /ujima/m2, sha-verified.\n"
               "[" (str/join "\n " (map pr-str entries)) "]\n"))
    (println "wrote" manifest-file (count entries) "jars")))


;; ── install! (chroot, no resolver) ──────────────────────────────────────────

(defn install!
  "Populate ROOT/ujima/m2 from PROJECT's manifest: plain downloads, sha-checked,
   skip what's already valid. Throws on any mismatch — the build fails, never
   ships a wrong jar."
  [{:keys [project root] :or {root "/"}}]
  (let [entries (edn/read-string (slurp (str project "/" manifest-file)))]
    (doseq [{:keys [path url] expected :sha256} entries
            :let [target (str root "/ujima/m2/" path)]]
      (when-not (and (fs/exists? target) (= expected (sha256 target)))
        (fs/create-dirs (fs/parent target))
        (p/shell "curl" "-fsSL" "--max-time" "120" "-o" target url)
        (let [got (sha256 target)]
          (when (not= expected got)
            (throw (ex-info "jar sha mismatch" {:jar path :expected expected :got got}))))))
    (println "bb deps:" (count entries) "jars in" (str root "/ujima/m2"))))
