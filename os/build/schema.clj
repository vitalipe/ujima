(ns build.schema
  "The pinned tz/xkb catalogs — generated namespaces under ujima.schema.*
   that runtime simply requires. generate! rewrites the pins from a system
   root; verify! is the os-build gate: the image's own files must match the
   pins exactly, or the build fails with the diff (regenerate + commit to
   accept a package drift)."
  (:require [clojure.string  :as str]
            [clojure.java.io :as io]))


(def ^:private zoneinfo-junk
  #{"posixrules" "leapseconds" "localtime" "SECURITY" "Factory" "+VERSION"})

(defn- zoneinfo-names
  ;; file-walk = systemd's own acceptance rule (timezone_is_valid checks the file)
  [root]
  (let [base (io/file root "usr/share/zoneinfo")]
    (->> (file-seq base)
         (filter (fn [f] (.isFile f)))
         (map (fn [f] (str (.relativize (.toPath base) (.toPath f)))))
         (remove (fn [p] (or (str/starts-with? p "posix/")
                             (str/starts-with? p "right/")
                             (str/includes? p ".")
                             (zoneinfo-junk p))))
         sort vec)))

(defn- xkb-layout-codes [root]
  (with-open [r (io/reader (io/file root "usr/share/X11/xkb/rules/evdev.lst"))]
    (->> (line-seq r)
         (drop-while (fn [l] (not= "! layout" l))) rest
         (take-while (fn [l] (re-find #"^\s+\S" l)))
         (map (fn [l] (first (str/split (str/trim l) #"\s+"))))
         sort vec)))


(def ^:private pins
  [{:ns 'schema.build.timezones   :file "runtime/src/schema/build/timezones.clj"   :read! zoneinfo-names}
   {:ns 'schema.build.xkb-layouts :file "runtime/src/schema/build/xkb_layouts.clj" :read! xkb-layout-codes}])

(defn- render [ns-sym names]
  (str "(ns " ns-sym "\n"
       "  \"GENERATED by build.schema (bb pin schema) — do not edit. The os build\n"
       "   fails unless the image's own catalogs match this pin.\")\n\n\n"
       "(def names\n"
       "  [" (str/join "\n   " (map pr-str names)) "])\n"))


(defn generate!
  "Rewrite the pins from a mounted image ROOTFS. Never this host: verify! diffs the
   pins against the image, so a host-derived pin can only ever fail the build — and
   until it does, it promises the runtime catalogs the device hasn't got."
  [root]
  (when (= "/" (.getCanonicalPath (io/file root)))
    (throw (ex-info "pin from a mounted image rootfs, not this host — the pin describes the image"
                    {:root (str root)})))
  (doseq [{:keys [ns file read!]} pins]
    (let [names (read! root)]
      (when (empty? names) (throw (ex-info "empty catalog" {:pin ns :root (str root)})))
      (io/make-parents file)
      (spit file (render ns names))
      (println "wrote" file (count names)))))


(defn- pinned [ns-sym]
  (require ns-sym)
  @(ns-resolve ns-sym 'names))

(defn verify!
  "The build gate: ROOT's catalogs vs the pinned namespaces, exact match."
  [root]
  (doseq [{:keys [ns read!]} pins]
    (let [pin  (set (pinned ns))
          live (set (read! root))]
      (when (not= pin live)
        (throw (ex-info (str ns " drifted from the pin — bb catalogs, review, commit")
                        {:pin        ns
                         :not-pinned (vec (sort (take 10 (remove pin live))))
                         :pin-only   (vec (sort (take 10 (remove live pin))))
                         :counts     {:pinned (count pin) :live (count live)}})))))
  {:verified (mapv :ns pins)})
